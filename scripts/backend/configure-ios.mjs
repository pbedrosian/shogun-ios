import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../', import.meta.url));
export function iosConfiguration(status, host = '127.0.0.1') {
  if (status.API_URL !== 'http://127.0.0.1:54321') throw new Error('Expected the local Supabase project.');
  const parts = host.split('.').map(Number);
  const localIP = parts.length === 4 && parts.every(n => Number.isInteger(n) && n >= 0 && n <= 255) &&
    (parts[0] === 127 || parts[0] === 10 || (parts[0] === 192 && parts[1] === 168) || (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31));
  if (!localIP && host !== 'localhost' && !/^[a-z0-9-]+\.local$/i.test(host)) throw new Error('Use a private IPv4 address, localhost, or a .local hostname.');
  const key = status.PUBLISHABLE_KEY || status.ANON_KEY;
  let publicKey = typeof key === 'string' && /^sb_publishable_[A-Za-z0-9_-]+$/.test(key);
  try { publicKey ||= JSON.parse(Buffer.from(key.split('.')[1], 'base64url')).role === 'anon'; } catch {}
  if (!publicKey || /[\r\n]/.test(key)) throw new Error('Local status did not contain a public client key.');
  return `// Generated by npm run ios:configure. Public client key only.\nSUPABASE_URL = http:/$()/${host}:54321\nSUPABASE_PUBLISHABLE_KEY = ${key}\n`;
}
export function configureIOS({ host = '127.0.0.1', onlyIfMissing = false } = {}) {
  const target = path.join(root, 'apps/ios/Configuration/Local.xcconfig');
  if (onlyIfMissing && existsSync(target)) return;
  const raw = execFileSync(path.join(root, 'node_modules/.bin/supabase'), ['--workdir', path.join(root, 'backend'), 'status', '-o', 'json'],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 20_000 });
  writeFileSync(target, iosConfiguration(JSON.parse(raw), host), { mode: 0o600 });
  console.log('Local iOS configuration is ready. Rebuild the app in Xcode.');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length && (args.length !== 2 || args[0] !== '--host')) throw new Error('Usage: npm run ios:configure [-- --host <Mac LAN IP>]');
    configureIOS({ host: args[1] });
  } catch { console.error('Could not configure iOS. Start local Supabase and use a private Mac LAN IP for --host.'); process.exitCode = 1; }
}
